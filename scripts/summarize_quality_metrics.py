"""Generate category-level quality metrics from a pytest JSON report."""

import argparse
import json
import sys
from pathlib import Path

from src.quality_metrics import build_quality_metrics


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Summarize pytest JSON results by overall outcome "
            "and configured test category."
        )
    )
    parser.add_argument(
        "--input",
        required=True,
        type=Path,
        help="Path to a JSON report generated by pytest-json-report.",
    )
    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="Path for the generated quality-metrics JSON summary.",
    )
    args = parser.parse_args()

    try:
        with args.input.open(encoding="utf-8") as report_file:
            report = json.load(report_file)

        metrics = build_quality_metrics(report)

        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open("w", encoding="utf-8") as output_file:
            json.dump(metrics, output_file, indent=2, sort_keys=True)
            output_file.write("\n")

    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"ERROR: unable to generate quality metrics: {exc}", file=sys.stderr)
        return 1

    overall = metrics["overall"]
    print(f"Input report: {args.input}")
    print(f"Quality summary: {args.output}")
    print(
        f"Executed: {overall['executed']}, "
        f"passed: {overall['passed']}, "
        f"failed: {overall['failed']}, "
        f"errors: {overall['errors']}, "
        f"skipped: {overall['skipped']}"
    )

    for category, summary in metrics["categories"].items():
        print(
            f"{category}: {summary['test_count']} tests, "
            f"{summary['passed']} passed, "
            f"{summary['failed']} failed, "
            f"{summary['errors']} errors"
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
